            "            self.state = {'next_epoch': 0, 'best_loss': None, 'reference_loss': None, 'wait': 0, 'stopped': False}\n",
            "\n",
            "    def on_epoch_end(self, epoch, logs=None):\n",
            "        logs = logs or {}\n",
            "        loss = float(logs['val_loss'])\n",
            "        if not math.isfinite(loss):\n",
            "            self.model.stop_training = True\n",
            "            return\n",
            "        if self.state['best_loss'] is None or loss < self.state['best_loss']:\n",
            "            temp = self.save_dir / 'best_temp.keras'\n",
